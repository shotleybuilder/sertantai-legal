defmodule SertantaiLegal.Scraper.Commencement.LeftoversReviewTest do
  @moduledoc """
  The commencement catalogues' leftovers (`Commencement.Leftovers`: words
  of a statement no rule uses), generated by `mix lat.commencement_patterns`
  and `mix lat.order_patterns` as `leftover_groups.json`, each reviewed in
  `leftovers.json`: `fix: <form>` (a reader miss, by reach), `known: <why>`
  (a named limit) or `check: <why>` (the check's own error, still open). A
  group with no status hasn't been reviewed and fails.
  """
  use ExUnit.Case, async: true

  @fixtures Path.expand("../../../fixtures", __DIR__)

  for catalogue <- ~w(commencement_patterns order_patterns) do
    @groups Path.join([@fixtures, catalogue, "leftover_groups.json"])
    @reviewed Path.join([@fixtures, catalogue, "leftovers.json"])
    @external_resource @groups
    @external_resource @reviewed

    test "#{catalogue}: every leftover group is reviewed (fix / known / check)" do
      groups = @groups |> File.read!() |> Jason.decode!()
      reviewed = @reviewed |> File.read!() |> Jason.decode!()

      unreviewed = for {shape, _} <- groups, not Map.has_key?(reviewed, shape), do: shape

      assert unreviewed == [],
             "#{length(unreviewed)} leftover groups not reviewed (add them to #{@reviewed}):\n  " <>
               Enum.join(Enum.sort(unreviewed), "\n  ")

      bad = for {shape, status} <- reviewed, not (status =~ ~r/^(?:fix|known|check): /), do: shape
      assert bad == [], "statuses must be fix: / known: / check: … — #{inspect(bad)}"
    end
  end
end
