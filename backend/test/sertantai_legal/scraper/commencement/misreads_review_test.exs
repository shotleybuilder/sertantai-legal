defmodule SertantaiLegal.Scraper.Commencement.MisreadsReviewTest do
  @moduledoc """
  The commencement catalogues' misreads (`Commencement.Misreads`: words of
  a statement a rule uses wrongly), generated by `mix
  lat.commencement_patterns` and `mix lat.order_patterns` as
  `misread_groups.json`, each reviewed in `misreads.json`: `fix: <form>` (a
  reader miss, by reach), `known: <why>` (a named limit) or `check: <why>`
  (the scan's own error, still open). A group with no status hasn't been
  reviewed and fails: "zero new patterns" as a code fact (Decision 1, Jason
  2026-11-20).
  """
  use ExUnit.Case, async: true

  @fixtures Path.expand("../../../fixtures", __DIR__)

  for catalogue <- ~w(commencement_patterns order_patterns) do
    @groups Path.join([@fixtures, catalogue, "misread_groups.json"])
    @reviewed Path.join([@fixtures, catalogue, "misreads.json"])
    @external_resource @groups
    @external_resource @reviewed

    test "#{catalogue}: every misread group is reviewed (fix / known / check)" do
      assert File.exists?(@groups),
             "#{@groups} not generated yet: run the catalogue with --accept (mix lat.#{unquote(catalogue)})"

      groups = @groups |> File.read!() |> Jason.decode!()
      reviewed = @reviewed |> File.read!() |> Jason.decode!()

      unreviewed = for {shape, _} <- groups, not Map.has_key?(reviewed, shape), do: shape

      assert unreviewed == [],
             "#{length(unreviewed)} misread groups not reviewed (add them to #{@reviewed}):\n  " <>
               Enum.join(Enum.sort(unreviewed), "\n  ")

      bad = for {shape, status} <- reviewed, not (status =~ ~r/^(?:fix|known|check): /), do: shape
      assert bad == [], "statuses must be fix: / known: / check: … — #{inspect(bad)}"
    end
  end
end
